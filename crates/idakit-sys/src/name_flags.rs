//! The typed [`NameFlags`] and [`RenameFlags`] layers over `name.hpp`'s `GN_*` and `SN_*` bits.

use std::ffi::c_int;

use bitflags::bitflags;

bitflags! {
    /// `get_ea_name`'s `gtn_flags` bits (`name.hpp`), controlling substitution/demangling.
    ///
    /// Accepts any bit pattern (`from_bits_retain`), so it stays sound as the raw `int` argument
    /// crossing to `get_ea_name`.
    #[derive(Clone, Copy, Debug, PartialEq, Eq, Hash, Default)]
    #[doc(alias(
        "GN_VISIBLE", "GN_COLORED", "GN_DEMANGLED", "GN_STRICT", "GN_SHORT", "GN_LONG",
        "GN_LOCAL", "GN_ISRET", "GN_NOT_ISRET", "GN_NOT_DUMMY"
    ))]
    pub struct NameFlags: c_int {
        /// Replace forbidden characters with `SUBSTCHAR` (`GN_VISIBLE`).
        #[doc(alias("GN_VISIBLE"))]
        const VISIBLE = 0x0001;
        /// Return a colored name (`GN_COLORED`).
        #[doc(alias("GN_COLORED"))]
        const COLORED = 0x0002;
        /// Return the demangled form (`GN_DEMANGLED`).
        #[doc(alias("GN_DEMANGLED"))]
        const DEMANGLED = 0x0004;
        /// Fail rather than fall back when demangling fails (`GN_STRICT`).
        #[doc(alias("GN_STRICT"))]
        const STRICT = 0x0008;
        /// Use the short demangled form (`GN_SHORT`).
        #[doc(alias("GN_SHORT"))]
        const SHORT = 0x0010;
        /// Use the long demangled form (`GN_LONG`).
        #[doc(alias("GN_LONG"))]
        const LONG = 0x0020;
        /// Try the local name first, falling back to the global one (`GN_LOCAL`).
        #[doc(alias("GN_LOCAL"))]
        const LOCAL = 0x0040;
        /// For a dummy name, use the return-location form (`GN_ISRET`).
        #[doc(alias("GN_ISRET"))]
        const ISRET = 0x0080;
        /// For a dummy name, do not use the return-location form (`GN_NOT_ISRET`).
        #[doc(alias("GN_NOT_ISRET"))]
        const NOT_ISRET = 0x0100;
        /// Do not return a dummy name (`GN_NOT_DUMMY`).
        #[doc(alias("GN_NOT_DUMMY"))]
        const NOT_DUMMY = 0x0200;
    }
}

bitflags! {
    /// `set_name`'s `flags` bits (`name.hpp`), controlling how a rename is validated and applied.
    ///
    /// Accepts any bit pattern (`from_bits_retain`), so it stays sound as the raw `int` argument
    /// crossing to `set_name`. `SN_CHECK` is `0`, so it is [`RenameFlags::empty`] rather than a
    /// constant: the empty set fails on an invalid character instead of replacing it.
    #[derive(Clone, Copy, Debug, PartialEq, Eq, Hash, Default)]
    #[doc(alias(
        "SN_CHECK", "SN_NOCHECK", "SN_PUBLIC", "SN_NON_PUBLIC", "SN_WEAK", "SN_NON_WEAK",
        "SN_AUTO", "SN_NON_AUTO", "SN_NOLIST", "SN_NOWARN", "SN_LOCAL", "SN_IDBENC", "SN_FORCE",
        "SN_NODUMMY", "SN_DELTAIL", "SN_MULTI", "SN_MULTI_FORCE"
    ))]
    pub struct RenameFlags: c_int {
        /// Replace invalid characters with `_` instead of failing (`SN_NOCHECK`).
        #[doc(alias("SN_NOCHECK"))]
        const NO_CHECK = 0x0001;
        /// Make the name public (`SN_PUBLIC`).
        #[doc(alias("SN_PUBLIC"))]
        const PUBLIC = 0x0002;
        /// Make the name non-public (`SN_NON_PUBLIC`).
        #[doc(alias("SN_NON_PUBLIC"))]
        const NON_PUBLIC = 0x0004;
        /// Make the name weak (`SN_WEAK`).
        #[doc(alias("SN_WEAK"))]
        const WEAK = 0x0008;
        /// Make the name non-weak (`SN_NON_WEAK`).
        #[doc(alias("SN_NON_WEAK"))]
        const NON_WEAK = 0x0010;
        /// Mark the name autogenerated (`SN_AUTO`).
        #[doc(alias("SN_AUTO"))]
        const AUTO = 0x0020;
        /// Mark the name non-autogenerated (`SN_NON_AUTO`).
        #[doc(alias("SN_NON_AUTO"))]
        const NON_AUTO = 0x0040;
        /// Exclude the name from the names list (`SN_NOLIST`).
        #[doc(alias("SN_NOLIST"))]
        const NO_LIST = 0x0080;
        /// Suppress the kernel warning on failure (`SN_NOWARN`).
        #[doc(alias("SN_NOWARN"))]
        const NO_WARN = 0x0100;
        /// Create a local name; a function must exist at the address (`SN_LOCAL`).
        #[doc(alias("SN_LOCAL"))]
        const LOCAL = 0x0200;
        /// Decode the name in the database encoding; implies [`NO_DUMMY`](Self::NO_DUMMY) (`SN_IDBENC`).
        #[doc(alias("SN_IDBENC"))]
        const DATABASE_ENCODING = 0x0400;
        /// If the name is taken, retry with a numeric suffix like `_123` (`SN_FORCE`).
        #[doc(alias("SN_FORCE"))]
        const FORCE = 0x0800;
        /// Prepend `_` to a name that begins with a dummy prefix such as `sub_` (`SN_NODUMMY`).
        #[doc(alias("SN_NODUMMY"))]
        const NO_DUMMY = 0x1000;
        /// Delete a hindering item when a tail byte blocks the name (`SN_DELTAIL`).
        #[doc(alias("SN_DELTAIL"))]
        const DELETE_TAIL = 0x2000;
        /// Keep an existing name as an "Alternative name" comment (`SN_MULTI`).
        #[doc(alias("SN_MULTI"))]
        const MULTI = 0x4000;
        /// Move an existing name into a comment and set the new one (`SN_MULTI_FORCE`).
        #[doc(alias("SN_MULTI_FORCE"))]
        const MULTI_FORCE = 0x8000;
    }
}

#[cfg(test)]
mod tests {
    use assert2::assert;
    use proptest::prelude::*;
    use rstest::rstest;

    use super::*;

    #[rstest]
    #[case::visible(NameFlags::VISIBLE, 0x0001)]
    #[case::colored(NameFlags::COLORED, 0x0002)]
    #[case::demangled(NameFlags::DEMANGLED, 0x0004)]
    #[case::strict(NameFlags::STRICT, 0x0008)]
    #[case::short(NameFlags::SHORT, 0x0010)]
    #[case::long(NameFlags::LONG, 0x0020)]
    #[case::local(NameFlags::LOCAL, 0x0040)]
    #[case::isret(NameFlags::ISRET, 0x0080)]
    #[case::not_isret(NameFlags::NOT_ISRET, 0x0100)]
    #[case::not_dummy(NameFlags::NOT_DUMMY, 0x0200)]
    fn flags_pin_the_raw_sdk_values(#[case] flag: NameFlags, #[case] raw: c_int) {
        assert!(flag.bits() == raw);
    }

    #[rstest]
    #[case::no_check(RenameFlags::NO_CHECK, 0x0001)]
    #[case::public(RenameFlags::PUBLIC, 0x0002)]
    #[case::non_public(RenameFlags::NON_PUBLIC, 0x0004)]
    #[case::weak(RenameFlags::WEAK, 0x0008)]
    #[case::non_weak(RenameFlags::NON_WEAK, 0x0010)]
    #[case::auto(RenameFlags::AUTO, 0x0020)]
    #[case::non_auto(RenameFlags::NON_AUTO, 0x0040)]
    #[case::no_list(RenameFlags::NO_LIST, 0x0080)]
    #[case::no_warn(RenameFlags::NO_WARN, 0x0100)]
    #[case::local(RenameFlags::LOCAL, 0x0200)]
    #[case::database_encoding(RenameFlags::DATABASE_ENCODING, 0x0400)]
    #[case::force(RenameFlags::FORCE, 0x0800)]
    #[case::no_dummy(RenameFlags::NO_DUMMY, 0x1000)]
    #[case::delete_tail(RenameFlags::DELETE_TAIL, 0x2000)]
    #[case::multi(RenameFlags::MULTI, 0x4000)]
    #[case::multi_force(RenameFlags::MULTI_FORCE, 0x8000)]
    fn rename_flags_pin_the_raw_sdk_values(#[case] flag: RenameFlags, #[case] raw: c_int) {
        assert!(flag.bits() == raw);
    }

    proptest! {
        #[test]
        fn from_bits_retain_round_trips_every_bit_pattern(raw: c_int) {
            prop_assert_eq!(NameFlags::from_bits_retain(raw).bits(), raw);
        }

        #[test]
        fn union_and_intersection_are_raw_bitwise_ops(a: c_int, b: c_int) {
            let (fa, fb) = (NameFlags::from_bits_retain(a), NameFlags::from_bits_retain(b));
            prop_assert_eq!((fa | fb).bits(), a | b);
            prop_assert_eq!((fa & fb).bits(), a & b);
        }

        #[test]
        fn complement_truncates_to_the_known_flag_mask(a: c_int) {
            let fa = NameFlags::from_bits_retain(a);
            prop_assert_eq!((!fa).bits(), !a & NameFlags::all().bits());
        }
    }
}
